extern int nondet_int(void);

void check_unique(void)
{
    char buf1[STRLEN + 1];
    char buf2[STRLEN + 1];
    int different = 0;

    for (size_t i = 0; i < STRLEN; ++i)
    {
        int c1 = nondet_int();
        int c2 = nondet_int();

        __CPROVER_assume(c1 == ' ' || (c1 >= 'a' && c1 <= 'z'));
        __CPROVER_assume(c2 == ' ' || (c2 >= 'a' && c2 <= 'z'));

        buf1[i] = (char)c1;
        buf2[i] = (char)c2;
        different |= (c1 != c2);
    }

    __CPROVER_assume(different);
    assert(crc64(0, (const unsigned char *)buf1, STRLEN) != crc64(0, (const unsigned char *)buf2, STRLEN));
}

